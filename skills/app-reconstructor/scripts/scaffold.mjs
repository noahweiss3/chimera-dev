export function scaffold({ chimeraDir, outDir, force = false }) {
  const entitiesPath = resolve(chimeraDir, "model/entities.json");
  const entitiesDoc = readJson(entitiesPath);
  if (!entitiesDoc?.entities) {
    return {
      status: "failed",
      error: "model/entities.json missing. Run model-inferrer first.",
    };
  }
  const entities = entitiesDoc.entities;

  const screensDoc = readJson(resolve(chimeraDir, "func-map/screens.json"));
  const screens = screensDoc?.screens ?? [];

  if (existsSync(outDir) && !force) {
    return {
      status: "aborted",
      reason: `${outDir} already exists. Pass force=true to overwrite.`,
    };
  }

  mkdirSync(outDir, { recursive: true });

  write(resolve(outDir, "package.json"), rootPackageJson());
  write(resolve(outDir, "pnpm-workspace.yaml"), workspaceYaml());
  write(resolve(outDir, "tsconfig.base.json"), tsconfigBase());
  write(resolve(outDir, ".gitignore"), gitignore());
  write(resolve(outDir, "README.md"), rootReadme());

  write(resolve(outDir, "apps/api/package.json"), apiPackageJson());
  write(resolve(outDir, "apps/api/tsconfig.json"), apiTsconfig());
  write(resolve(outDir, "apps/api/drizzle.config.ts"), drizzleConfig());
  write(resolve(outDir, "apps/api/src/index.ts"), apiIndex(entities));
  write(resolve(outDir, "apps/api/src/db/client.ts"), dbClient());

  const schemaSrc = resolve(chimeraDir, "model/schema.ts");
  if (existsSync(schemaSrc)) {
    mkdirSync(resolve(outDir, "apps/api/src/db"), { recursive: true });
    copyFileSync(schemaSrc, resolve(outDir, "apps/api/src/db/schema.ts"));
  } else {
    write(
      resolve(outDir, "apps/api/src/db/schema.ts"),
      `// TODO(chimera): model-inferrer did not produce schema.ts. Reconstruct it from .chimera/model/entities.json.\n`
    );
  }

  for (const entity of entities) {
    write(
      resolve(outDir, `apps/api/src/routes/${entity.table}.ts`),
      routeStub(entity)
    );
  }

  write(resolve(outDir, "apps/web/package.json"), webPackageJson());
  write(resolve(outDir, "apps/web/tsconfig.json"), webTsconfig());
  write(resolve(outDir, "apps/web/vite.config.ts"), viteConfig());
  write(resolve(outDir, "apps/web/index.html"), indexHtml());
  write(resolve(outDir, "apps/web/src/main.tsx"), mainTsx());
  write(resolve(outDir, "apps/web/src/App.tsx"), appTsx(screens));
  write(resolve(outDir, "apps/web/src/lib/api.ts"), apiClientStub());

  for (const screen of screens) {
    const name = pascalCase(screen.name);
    write(resolve(outDir, `apps/web/src/pages/${name}.tsx`), pageStub(screen));
  }

  write(resolve(outDir, "packages/shared/package.json"), sharedPackageJson());
  write(resolve(outDir, "packages/shared/tsconfig.json"), sharedTsconfig());
  write(resolve(outDir, "packages/shared/src/schemas.ts"), sharedSchemasStub());

  const llmTodos = [
    "Fill in CRUD handlers in apps/api/src/routes/<entity>.ts using OpenAPI spec + Drizzle schema",
    "Implement page components in apps/web/src/pages/<Screen>.tsx",
    "Generate typed fetch client in apps/web/src/lib/api.ts from .chimera/api-spec/openapi.json",
    "Generate Zod schemas in packages/shared/src/schemas.ts from .chimera/model/entities.json",
  ];

  return {
    status: "done",
    entities_scaffolded: entities.length,
    screens_scaffolded: screens.length,
    files_written: 14 + entities.length + screens.length,
    llm_todos: llmTodos,
    output_dir: outDir,
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const chimeraDir = resolve(process.cwd(), ".chimera");
  const outDir = resolve(process.cwd(), "chimera-clone");
  const force = process.argv.includes("--force");
  if (!existsSync(chimeraDir)) {
    console.error(JSON.stringify({ error: "No .chimera/ directory in cwd." }));
    process.exit(1);
  }
  console.log(JSON.stringify(scaffold({ chimeraDir, outDir, force }), null, 2));
}
