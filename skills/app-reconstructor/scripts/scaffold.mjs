function apiIndex(entities) {
  const importLines = entities
    .map((e) => `import ${e.table}Routes from "./routes/${e.table}.js";`)
    .join("\n");
  const useLines = entities
    .map((e) => `app.use("/api/${e.table}", ${e.table}Routes);`)
    .join("\n");
  return `import express from "express";
${importLines}

const app = express();
app.use(express.json());

${useLines}

app.get("/health", (_req, res) => res.json({ status: "ok" }));

const port = Number(process.env.API_PORT ?? 4000);
app.listen(port, () => console.log(\`api listening on \${port}\`));
`;
}

